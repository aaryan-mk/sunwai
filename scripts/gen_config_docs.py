"""Generate ``docs/configuration.md`` from the typed settings.

Usage: ``python scripts/gen_config_docs.py > docs/configuration.md``.
"""

from __future__ import annotations

from sunwai.core.config import Settings
from sunwai.core.legacy_env import LEGACY_VARS


def main() -> None:
    """Print the configuration reference as Markdown."""
    settings = Settings()
    print("# Configuration reference\n")
    print("Generated by `scripts/gen_config_docs.py`; do not edit by hand.\n")
    print("Every setting defaults to *unset*, which means the engine's built-in default applies. A canonical name")
    print(
        "(`SUNWAI_<GROUP>__<FIELD>`) overrides the legacy flat name. Booleans accept `true/false/1/0/yes/no/on/off`.\n"
    )
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for var in LEGACY_VARS:
        field = type(getattr(settings, var.group)).model_fields[var.field]
        groups.setdefault(var.group, []).append(
            (var.canonical, var.name, (field.description or "").split(" Legacy name")[0])
        )
    for group, rows in groups.items():
        doc = (type(getattr(settings, group)).__doc__ or "").strip()
        print(f"## {group}\n\n{doc}\n")
        print("| Canonical name | Legacy name | Purpose |\n|---|---|---|")
        for canonical, legacy, purpose in rows:
            print(f"| `{canonical}` | `{legacy}` | {purpose} |")
        print()


if __name__ == "__main__":
    main()
